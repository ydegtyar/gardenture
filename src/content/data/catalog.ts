export function getXpRequiredForLevel(level: number): number {
  const idx = Math.max(0, level - 1);
  if (idx < XP_TO_NEXT_LEVEL.length) {
    return XP_TO_NEXT_LEVEL[idx]!;
  }
  return 188 + (idx - XP_TO_NEXT_LEVEL.length + 1) * 32;
}

